def set_language(lang_code):
    global _current_lang
    if lang_code in LANGUAGES:
        _current_lang = lang_code
    else:
        _current_lang = "tr"

def get_language():
    return _current_lang

def tr(key):
    lang_dict = TRANSLATIONS.get(_current_lang, TRANSLATIONS["tr"])
    if key in lang_dict:
        return lang_dict[key]
    return TRANSLATIONS["tr"].get(key, key)

def get_license_file(program_dir):
    # SADECE Turkce icin GPLv3_TR.html, Turkce disindaki TUM dillerde GPLv3_EN.html
    if _current_lang == "tr":
        return os.path.join(program_dir, "GPLv3_TR.html").replace("\\", "/")
    return os.path.join(program_dir, "GPLv3_EN.html").replace("\\", "/")

def detect_system_language():
    try:
        sys_locale = QtCore.QLocale.system().name()
        lang_prefix = sys_locale.split("_")[0].lower()
        if lang_prefix in LANGUAGES:
            return lang_prefix
    except Exception:
        pass
    return "tr"

def format_current_prayer(prayer_key):
    p_name = tr(prayer_key)
    fmt = tr("simdi_vakti_fmt")
    if "%1" in fmt:
        return fmt.replace("%1", p_name)
    return f"Şimdi {p_name} Vakti"

def format_remaining_time(prayer_key):
    p_name = tr(prayer_key)
    fmt = tr("kalan_sure_fmt")
    if "%1" in fmt:
        return fmt.replace("%1", p_name)
    return f"{p_name}'e Kalan Süre :"

def format_remaining_short(prayer_key):
    p_name = tr(prayer_key)
    fmt = tr("kalan_kisa_fmt")
    if "%1" in fmt:
        return fmt.replace("%1", p_name)
    return f"{p_name}'e Kalan"

def day_name(day_of_week):
    d = ((int(day_of_week) - 1) % 7) + 1
    return tr(f"gun_{d}")

def weather_description(code):
    lang = _current_lang
    w_dict = WEATHER_CONDITIONS.get(lang, WEATHER_CONDITIONS.get("tr", {}))
    return w_dict.get(code, w_dict.get("default", "Açık"))
